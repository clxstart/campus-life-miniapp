-- AI 陪聊规则表（关键词匹配）
-- 手动执行；可重复执行。
--
-- 背景：用户要一个「关键词匹配就行」的 AI 聊天，不接大模型。
-- 规则存数据库，管理端后续可维护；匹配不到时走兜底话术。
--
-- 匹配策略：一条规则可以有多个关键词（逗号分隔），命中任意一个即算匹配；
-- 多条规则同时命中时，priority 大的优先（同优先级取关键词更长的，更精确）。
USE campus_life;

CREATE TABLE IF NOT EXISTS ai_chat_rule (
  id           BIGINT PRIMARY KEY AUTO_INCREMENT,
  category     VARCHAR(32)  NOT NULL COMMENT '分类：greeting/study/food/sleep/mood/campus/help/fallback',
  keywords     VARCHAR(255) NOT NULL COMMENT '关键词，逗号分隔；命中任意一个即匹配',
  reply        VARCHAR(500) NOT NULL COMMENT '回复话术',
  quick_replies VARCHAR(255) NULL COMMENT '快捷追问，逗号分隔（前端渲染成按钮）',
  priority     INT          NOT NULL DEFAULT 0 COMMENT '数值越大越优先',
  status       TINYINT      NOT NULL DEFAULT 1,
  created_at   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_ai_rule_category (category, status, priority)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT 'AI 陪聊关键词规则';

